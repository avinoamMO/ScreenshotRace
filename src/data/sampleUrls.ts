// Generate expanded URL list with path variations
export const EXPANDED_URLS: string[] = [];

for (const url of ALL_SAMPLE_URLS) {
  for (const path of PATH_VARIATIONS) {
    EXPANDED_URLS.push(url + path);
  }
}

// Utility to get random URLs from the pool
export function getRandomUrls(count: number): string[] {
  const shuffled = [...EXPANDED_URLS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, EXPANDED_URLS.length));
}

